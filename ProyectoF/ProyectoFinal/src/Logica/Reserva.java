package Logica;

public class Reserva {
    String codigo;
    String huesped;
    String habitacion;
    String fechaEntrada;
    String fechaSalida;
    String estado;

    public Reserva(String codigo, String huesped, String habitacion, String fechaEntrada, String fechaSalida, String estado) {
        this.codigo = codigo;
        this.huesped = huesped;
        this.habitacion = habitacion;
        this.fechaEntrada = fechaEntrada;
        this.fechaSalida = fechaSalida;
        this.estado = estado;
    }
    
    
    
    
}
