package Logica;

public class Habitacion {
    
    private String numero;
    private String capacidad;   
    private String precioNoche;
    private String estado;
    private String tipo;

    public Habitacion(String numero, String capacidad, String precioNoche, String estado, String tipo) {
        this.numero = numero;
        this.capacidad = capacidad;
        this.precioNoche = precioNoche;
        this.estado = estado;
        this.tipo = tipo;
    }

    
    
    
}
